package dev.rubentxu.pipeline.v2.credentials.api

import dev.rubentxu.pipeline.v2.domain.SecretHandle
import java.util.Base64
import java.util.regex.Pattern

/**
 * Registry for secret patterns used by [RedactingEventSink] to scrub secrets
 * from free-text event fields.
 * ## Multi-form Pattern Generation
 * Each registered secret generates patterns for multiple encodings:
 * Literal: the raw secret bytes as
 * - base64 std: Base64 standard encoder (with padding)
 * - base64 url-safe: Base64 URL-safe encoder (no padding)
 * - base64 trimmed padding/last-char: the secret printed without its base64 padding
 * - hex upper: uppercase hex (2 chars per byte)
 * - hex lower: lowercase hex (2 chars per byte)
 * - URL-encoded: percent-encoded special chars
 * ## Single Generation Seam
 * All literal variants are generated by [generateEncodedVariants] and fed to
 * both [buildActivePatterns] (for scrub) and [maxPatternLength] (for carry-window
 * computation). This ensures consistent enumeration without duplication.
 * ## Two Seams Over The Same Variants
 * The variants feed two seams, and they answer two different questions.
 * - [literalSeam] holds the whole variants, and [buildActivePatterns] scrubs them out of
 *   a text that holds them whole.
 * - [fragmentSeam] holds the windows of the variants, and [StreamingRedactor] matches
 *   them against a stream that delivers a value in pieces.
 * A value that arrives whole is covered by its own fragments as well, because the
 * fragments that fall inside it cover it entirely: the value does not need to be a
 * pattern of its own to be masked.
 * ## Minimum Maskable Length
 * Per GitLab rule, secrets shorter than [MIN_MASKABLE_LENGTH] are NOT registered for masking, and
 * the discard is SILENT: nothing is thrown, nothing is reported, and the value is never
 * registered, so no masking pattern is ever built for it.
 * ## What this means for a caller, stated plainly
 * A bound credential whose secret is shorter than [MIN_MASKABLE_LENGTH] runs normally and its value
 * appears in the transcript IN THE CLEAR. The threshold governs MASKING, not VALIDITY — a short
 * password is a weak password, not a malformed one, and refusing it would reject credentials that
 * work perfectly well. So the product accepts the binding and the redaction simply does not apply.
 * ## Who reports the short secret
 * The REGISTRY discards the value in silence, because it cannot report: [addSecret] reads
 * through `SecretHandle.peek`, a non-consuming observer whose contract cannot carry a result
 * out, and adding a result to a published signature would make this type answer a second
 * question about redaction.
 * The REPORT is made by the seam that BOUNDS the credential, which is the one place that knows
 * which credential the value belongs to: it builds
 * [SecretShorterThanMinimumMaskableLengthWarning] and hands it to the operator's console. The
 * report carries the credential id and the length, never the value.
 * So the silence here is not the end of the story: it is the half of it that belongs to the
 * registry. The other half belongs to the binding, and the binding makes it.
 * ## Performance
 * - The scrub is a list of [Pattern.quote] alternations, one per literal variant, and it
 *   runs once per free-text field of an event.
 * - The streaming redactor matches the fragments of the variants through their bytes, so
 *   the number of patterns a value contributes does not multiply the cost of a byte.
 * ## The seam version
 * The registry declares WHEN its seam changed: the seam version moves every time the
 * registered values change, and it does not move when they do not. A consumer that
 * captured the seam can therefore tell, with one read, that what it holds is no longer
 * what the registry holds — which is what lets a redactor that must hold its state
 * across fragments reload the seam instead of rebuilding itself.
 * The version is a NUMBER and not a snapshot: the snapshot is what the redactor rebuilds
 * when the number moves, and the number is what it reads on every fragment.
 * ## The values and the readers
 * The registered values are written by the thread that resolves a binding and read by
 * the threads that scrub transcripts, and those are not the same thread: a value that is
 * registered while a transcript is being scrubbed must not tear the set the scrubber
 * walks. Every read and every write of the values goes through one lock, and the
 * version moves under that lock, after the values have moved.
 * @see RedactingEventSink for the decorator that applies these patterns
*/
class SecretPatternRegistry {

    /**
     * The lock that guards the registered values and their version.
     */
    private val lock = Any()

    private val registeredSecrets = mutableSetOf<String>()

    /**
     * The version of the seam: it moves when the registered values change, and it stays
     * where it is when a registration changes nothing.
     *
     * It is read on every fragment a redactor scrubs, so it is a plain read of a
     * volatile field and not a walk of the values.
     */
    @Volatile
    internal var seamVersion: Int = 0
        private set

    /**
     * Registers a secret for masking.
     * Observes the bytes without consuming the handle. This method used to call `use`, which
     * WIPED the handle on return — so registering a bound credential destroyed the credential.
     * The canary call sites never noticed, because they register handles they just built and
     * throw away; a call site that registers a handle the pipeline still owns would have found
     * its secret zeroed out before `sh` ran.
     * @param handle The [SecretHandle] wrapping the secret bytes
*/
    fun addSecret(handle: SecretHandle) {
        handle.peek { bytes -> addSecretValue(String(bytes, Charsets.UTF_8)) }
    }

    /**
     * Registers an already-materialised secret value for masking.
     * The seam for a caller that HAS the bytes but no handle — a value read out of a credential
     * binding, or one record of a large file-backed secret.
     * Values below [MIN_MASKABLE_LENGTH] are not registered: a literal that short collides with
     * ordinary output, and a redactor that scrubs four characters everywhere destroys more
     * observability than it protects.
*/
    fun addSecretValue(secretValue: String) {
        if (secretValue.length < MIN_MASKABLE_LENGTH) {
            // Silently unregistered, NOT refused: the caller gets no error and the secret stays
            // usable, it just is not masked. See the class KDoc — there is no channel here to
            // report it, and inventing one would mean a second redaction authority.
            return
        }

        synchronized(lock) {
            // The version moves only when the seam moved: a value that was already
            // registered leaves the seam exactly as it was.
            if (registeredSecrets.add(secretValue)) seamVersion++
        }
    }

    /**
     * Registers every RECORD of a multi-line secret for masking.
     * ## Why this exists rather than [addSecretValue]
     * [maxLiteralByteLength] is the MAXIMUM over everything registered, and it is the
     * `StreamingRedactor` lookahead — so a single 3 KB SSH key registered whole makes the redactor
     * hold 6 KB before emitting any byte, on every step of the run. Registering the whole document
     * is what made that cost real. Registering it RECORD BY RECORD bounds the window at
     * `2 x longest record`: OpenSSH and PEM wrap base64 at 70 columns, so a real key costs a
     * ~140-byte window instead of ~6 KB.
     * ## What this does and does not catch
     * It catches a record appearing in output, which is exactly what `cat $KEY_FILE`, `git` or any
     * other consumer of a text-format credential emits: the newlines that split the records are
     * the newlines the output carries. A record with no trailing newline still registers — the
     * reader, not the delimiter, defines the record.
     * It does NOT catch a secret *constructed* across records (e.g. base64 re-wrapped by the
     * consumer at a different column width). That is a real and accepted gap: it needs a
     * re-chunking redactor, not a bigger literal.
*/
    fun addSecretRecords(content: String) {
        synchronized(lock) {
            var changed = false
            for (record in content.lineSequence()) {
                if (record.length >= MIN_MASKABLE_LENGTH) {
                    if (registeredSecrets.add(record)) changed = true
                }
            }
            if (changed) seamVersion++
        }
    }

    /**
     * Removes a secret from the registry.
     * @param handle The [SecretHandle] wrapping the secret bytes
*/
    fun removeSecret(handle: SecretHandle) {
        val secretValue = handle.use { bytes ->
            String(bytes, Charsets.UTF_8)
        }
        synchronized(lock) {
            if (registeredSecrets.remove(secretValue)) seamVersion++
        }
    }

    /**
     * Generates all encoded variants for a single secret.
     * This is the SINGLE generation seam — feeds both [buildActivePatterns]
     * and [maxPatternLength] to ensure consistent enumeration.
     * Variants generated (same set for both paths):
     * 1. Literal
     * 2. base64 std (with padding)
     * 3. base64 url-safe (no padding)
     * 4. base64 trimmed padding variants (padding stripped, as a log line often prints it)
     * 5. hex upper
     * 6. hex lower
     * 7. URL-encoded (only if secret contains chars needing encoding)
     * @param secret The secret string to encode
     * @return List of all encoded variant strings
*/
    private fun generateEncodedVariants(secret: String): List<String> {
        val variants = mutableListOf<String>()
        val rawBytes = secret.toByteArray(Charsets.UTF_8)

        // 1. Literal
        variants.add(secret)

        // 2. base64 std (with padding)
        val b64Std = Base64.getEncoder().encodeToString(rawBytes)
        variants.add(b64Std)

        // 3. base64 url-safe (no padding)
        variants.add(Base64.getUrlEncoder().withoutPadding().encodeToString(rawBytes))

        // 4. base64 trimmed padding variants (padding stripped, as a log line often prints it)
        if (b64Std.endsWith("==")) {
            variants.add(b64Std.removeSuffix("=="))   // -2 chars
            variants.add(b64Std.dropLast(2))           // same as above, explicit
        } else if (b64Std.endsWith("=")) {
            variants.add(b64Std.removeSuffix("="))     // -1 char
        }

        // 5. hex upper
        variants.add(rawBytes.joinToString("") { "%02X".format(it) })

        // 6. hex lower
        variants.add(rawBytes.joinToString("") { "%02x".format(it) })

        // 7. URL-encoded (only if secret contains chars needing encoding)
        val urlEncoded = buildUrlEncodedVariant(secret)
        if (urlEncoded.isNotEmpty() && urlEncoded != secret) {
            variants.add(urlEncoded)
        }

        return variants
    }

    /**
     * Builds the active list of [Regex] patterns for all registered secrets.
     * One quoted alternation per literal variant, which is what a whole text is scrubbed
     * with: the text either holds the value whole or it does not hold it at all.
     * @return List of [Regex] patterns — empty if no secrets registered
*/
    internal fun buildActivePatterns(): List<Regex> {
        val seam = literalSeam()
        if (seam.isEmpty()) return emptyList()

        val patterns = mutableListOf<Regex>()
        for (literal in seam) {
            patterns.add(Pattern.quote(String(literal, Charsets.UTF_8)).toRegex())
        }
        return patterns
    }

    /**
     * Returns the ordered seam of encoded literal byte arrays, longest-first
     * With deterministic tie-break (lexicographic order of the representation)
     * The seam holds every literal variant once: the variants of two secrets can be the
     * same bytes, and a seam that repeats them makes the scrub do the same work twice.
     * @return Ordered list of literal byte arrays, empty when no secrets are registered
*/
    internal fun literalSeam(): List<ByteArray> {
        synchronized(lock) {
            return literalSeamOfRegisteredValues()
        }
    }

    /**
     * The seam of the registered values, read under the lock that guards them.
     */
    private fun literalSeamOfRegisteredValues(): List<ByteArray> {
        if (registeredSecrets.isEmpty()) {
            // An EMPTY registry is a PASSTHROUGH, and it says so by having no
            // literals at all.
            // This used to return `listOf(SCRUB_MARKER)` — a synthetic four-byte literal. The
            // comment claimed it "cannot match any real data", which was wrong in a way that
            // mattered twice over: real output DOES contain `****` (it is what the marker looks
            // like, and it is a perfectly ordinary thing for a child process to print), and the
            // sentinel forced a MIN_SECRET_WINDOW lookahead on a stream that had no secret to
            // look for. With no literals every head is undecidable, so the redactor held bytes it
            // did not have to hold — and a full ring is exactly the state that used to spin.
            // A registry with nothing to redact has nothing to decide, so it decides nothing.
            return emptyList()
        }

        val seam = mutableListOf<ByteArray>()
        for (secret in registeredSecrets) {
            for (variant in generateEncodedVariants(secret)) {
                seam.add(variant.toByteArray(Charsets.UTF_8))
            }
        }

        // Sort longest-first; tie-break by lexicographic byte order for determinism
        seam.sortWith(
            compareByDescending<ByteArray> { it.size }
                .thenComparator { a, b ->
                    val minLen = minOf(a.size, b.size)
                    for (i in 0 until minLen) {
                        val diff = (a[i].toInt() and 0xFF) - (b[i].toInt() and 0xFF)
                        if (diff != 0) return@thenComparator diff
                    }
                    a.size - b.size
                }
        )
        return distinctByBytes(seam)
    }

    /**
     * Returns the seam of FRAGMENTS: every window of [fragmentThresholdBytes] bytes that
     * falls inside an encoded variant of a registered secret.
     *
     * ## Why fragments and not the whole variants
     * A value that the flow delivers in pieces is not a contiguous string in the stream:
     * the bytes of one half arrive, then bytes that are not part of the value, then the
     * bytes of the other half. A matcher that only knows the whole value cannot see it
     * there, because the value it is looking for is not a string that exists. The
     * fragments are what the value looks like when it is cut: the windows that fall
     * inside it, each of them a piece of the value that is still long enough to be worth
     * hiding.
     *
     * ## Why the value is still masked whole
     * The fragments that fall inside a value cover it entirely, so a value that arrives
     * whole is covered by its own fragments and needs no pattern of its own. The
     * fragments of the encoded variants cover their variant for the same reason, which
     * is why a base64, hexadecimal or URL-encoded value is masked whole too.
     *
     * ## What the threshold means
     * The threshold counts BYTES, because the seam is bytes and a value that is not ASCII
     * has more bytes than characters. A variant shorter than the threshold contributes no
     * fragment, and a value whose fragments are all shorter than the threshold is not
     * masked at all: that is the promise the threshold makes.
     *
     * @param fragmentThresholdBytes The number of bytes a fragment must have to be matched.
     * @return The fragments, each of them exactly [fragmentThresholdBytes] bytes long,
     *   without repetition, in a deterministic order.
    */
    internal fun fragmentSeam(fragmentThresholdBytes: Int): List<ByteArray> {
        require(fragmentThresholdBytes > 0) {
            "a fragment threshold of $fragmentThresholdBytes bytes masks nothing"
        }
        synchronized(lock) {
            return fragmentSeamOfRegisteredValues(fragmentThresholdBytes)
        }
    }

    /**
     * The fragments of the registered values, read under the lock that guards them.
     */
    private fun fragmentSeamOfRegisteredValues(fragmentThresholdBytes: Int): List<ByteArray> {
        if (registeredSecrets.isEmpty()) return emptyList()

        val fragments = mutableListOf<ByteArray>()
        for (secret in registeredSecrets) {
            for (variant in generateEncodedVariants(secret)) {
                val bytes = variant.toByteArray(Charsets.UTF_8)
                if (bytes.size < fragmentThresholdBytes) continue
                for (start in 0..bytes.size - fragmentThresholdBytes) {
                    fragments.add(bytes.copyOfRange(start, start + fragmentThresholdBytes))
                }
            }
        }
        // The fragments are the same length, so their order is decided by their bytes: the
        // seam a redactor captures must not depend on the order a secret was registered.
        return distinctByBytes(fragments).sortedBy { it.toByteArrayKey() }
    }

    /**
     * The bytes of a byte array as a key that compares by CONTENT.
     *
     * A [ByteArray] compares by identity, so two arrays with the same bytes are two
     * different keys, and a set of them never removes a repetition. The key is the same
     * bytes read as Latin-1, where every byte is one character and no byte is lost.
     */
    private fun ByteArray.toByteArrayKey(): String = String(this, Charsets.ISO_8859_1)

    /**
     * The elements of [elements] without repetition, compared by their bytes.
     */
    private fun distinctByBytes(elements: List<ByteArray>): List<ByteArray> {
        val seen = HashSet<String>()
        val distinct = mutableListOf<ByteArray>()
        for (element in elements) {
            if (seen.add(element.toByteArrayKey())) distinct.add(element)
        }
        return distinct
    }

    /**
     * Returns the maximum encoded literal byte length across all registered secrets.
     * Used by [StreamingRedactor] to bound the pending buffer and ensure enough
     * lookahead exists to rule out any secret match before emitting a byte.
     * When no secrets are registered, returns [MIN_SECRET_WINDOW] (a safe floor).
     * @return Maximum literal byte length, floored at [MIN_SECRET_WINDOW]
*/
    internal fun maxLiteralByteLength(): Int {
        synchronized(lock) {
            return maxLiteralByteLengthOfRegisteredValues()
        }
    }

    /**
     * The window the registered values need, read under the lock that guards them.
     */
    private fun maxLiteralByteLengthOfRegisteredValues(): Int {
        // With no literals the lookahead is ONE byte, not MIN_SECRET_WINDOW.
        // A one-byte ring is fully decided the moment its byte arrives (no literal can start
        // with it, because there are no literals), so the ring never fills and never withholds.
        // That is what "a registry without secrets preserves the bytes exactly" needs, and it is
        // why 1 rather than 0: a zero-length ring has no byte to hold, and feed/take would have
        // nothing to move.
        if (registeredSecrets.isEmpty()) return 1

        var maxLen = 0
        for (secret in registeredSecrets) {
            for (variant in generateEncodedVariants(secret)) {
                maxLen = maxOf(maxLen, variant.toByteArray(Charsets.UTF_8).size)
            }
        }
        return maxOf(maxLen, MIN_SECRET_WINDOW)
    }

    /**
     * Returns the number of registered secrets.
*/
    fun size(): Int = synchronized(lock) { registeredSecrets.size }

    /**
     * Computes the rolling secret-window size for [StreamingRedactor].
     * The window equals `max(generatedPatternLiteralLength) - 1` over all
     * registered secrets and all encoding variants. Uses the SAME [generateEncodedVariants]
     * seam as [buildActivePatterns] to ensure consistent enumeration without duplication.
     * Per the [StreamingRedactor] byte-window redaction algorithm:
     * - `secret_window = max(registeredPatternLiteralLength) - 1`
     * - `buffer capacity = secret_window + chunkSize`
     * The floor is 7 bytes: the shortest registered secret is 8 bytes
     * ([MIN_MASKABLE_LENGTH]), and hex encoding of 8 bytes yields 16 chars,
     * so `16 - 1 = 15`. If no secrets are registered, a default window
     * of 7 is returned (enough to catch any split match of the minimum
     * pattern size).
     * @return the maximum encoded pattern literal length minus 1, floored at 7
*/
    internal fun maxPatternLength(): Int {
        synchronized(lock) {
            return maxPatternLengthOfRegisteredValues()
        }
    }

    /**
     * The rolling window of the registered values, read under the lock that guards them.
     */
    private fun maxPatternLengthOfRegisteredValues(): Int {
        if (registeredSecrets.isEmpty()) return MIN_SECRET_WINDOW

        var maxLen = 0
        for (secret in registeredSecrets) {
            for (variant in generateEncodedVariants(secret)) {
                maxLen = maxOf(maxLen, variant.length)
            }
        }

        return maxOf(maxLen - 1, MIN_SECRET_WINDOW)
    }

    /**
     * Builds the URL-encoded variant of a secret.
     * Characters that require encoding are percent-encoded; every other character is
     * copied verbatim. A secret needing no encoding therefore comes back UNCHANGED,
     * not empty, and [generateEncodedVariants] is what declines to register it — its
     * `urlEncoded != secret` test is the seam that skips a redundant duplicate of the
     * literal pattern.
*/
    private fun buildUrlEncodedVariant(secret: String): String {
        val sb = StringBuilder()
        for (ch in secret) {
            // A character that does not need encoding is COPIED, not dropped. A secret is
            // mostly letters and digits, so "replace the ones that need it" has to mean
            // "keep the rest": dropping them made `p@ss w0rd` encode to `%40%20`, a
            // pattern that matches neither the encoded secret (`p%40ss%20w0rd`, which
            // therefore passed through unredacted) nor anything else that carries the
            // credential — while matching any unrelated text that happens to hold those
            // two encodings adjacent. `generateEncodedVariants` already guards with
            // `urlEncoded != secret`, which was unreachable while every unreserved
            // character was discarded, and is the seam that skips a secret needing no
            // encoding at all.
            sb.append(URL_ENCODE_CHARS[ch] ?: ch.toString())
        }
        return sb.toString()
    }

    /**
     * Scrubs all registered secret patterns from a string.
     * This is a standalone scrub for use cases like `GitCheckoutFailed.reason`
     * where the error message may contain embedded credentials that need to be
     * redacted before the event is emitted.
     * `GitCheckoutFailed.reason` must be scrubbed via this method
     * before construction of the event.
     * @param input The string to scrub
     * @return The scrubbed string with all registered secrets replaced by "****"
*/
    fun scrub(input: String): String {
        val patterns = buildActivePatterns()
        if (patterns.isEmpty()) return input

        var result = input
        for (pattern in patterns) {
            result = pattern.replace(result, SCRUB_MARKER)
        }
        return result
    }

    /**
     * The seam of the registry as it is NOW, read in one step.
     *
     * The three things a redactor needs travel together because a redactor that read
     * them in two steps could pair the version of one seam with the fragments of
     * another, and would then believe it had reloaded when it had not.
     *
     * @param fragmentThresholdBytes The number of bytes a fragment must have to be matched.
     * @return The fragments, the window they need and the version they belong to.
     */
    internal fun seamSnapshot(fragmentThresholdBytes: Int): SeamSnapshot = synchronized(lock) {
        SeamSnapshot(
            version = seamVersion,
            fragments = fragmentSeamOfRegisteredValues(fragmentThresholdBytes),
            maxLiteralByteLength = maxLiteralByteLengthOfRegisteredValues(),
        )
    }

    /**
     * The seam of the registry at one moment: the fragments a redactor matches, the
     * window they need to hold, and the version that says which seam this is.
     *
     * The version is what a redactor compares against the one it captured: when they
     * differ, the seam moved, and the redactor reloads it.
     */
    internal data class SeamSnapshot(
        /** The version of the seam this snapshot belongs to. */
        val version: Int,
        /** The fragments of the registered values, each of them a window of the threshold. */
        val fragments: List<ByteArray>,
        /** The window the longest encoded literal needs. */
        val maxLiteralByteLength: Int,
    )

    /**
     * The thresholds and the marker the registry works by.
     *
     * [MIN_MASKABLE_LENGTH] is the shortest value worth masking and [MIN_SECRET_WINDOW] the floor
     * of the lookahead a streaming redactor needs. [SCRUB_MARKER] is what a masked value is
     * replaced by. They are public because a caller that reports on redaction needs to state the
     * same thresholds the registry applies, not a copy of them.
     */
    companion object {
        /**
         * GitLab minimum maskable secret length.
         * Secrets below this threshold are NOT registered for masking.
*/
        const val MIN_MASKABLE_LENGTH = 8

        /**
         * Default minimum secret window for [StreamingRedactor].
         * Floor: the shortest registered secret is 8 bytes ([MIN_MASKABLE_LENGTH]);
         * hex encoding doubles this to 16 chars; `16 - 1 = 15`. If no secrets are
         * registered, this floor ensures the redactor can still process chunks
         * without under-running the buffer.
*/
        const val MIN_SECRET_WINDOW = 7

        /**
         * Marker used to replace scrubbed secret values.
*/
        const val SCRUB_MARKER = "****"

        /**
         * URL-encodes a string for the common special chars in secrets.
*/
        private val URL_ENCODE_CHARS = mapOf(
            '+' to "%2B",
            '/' to "%2F",
            '=' to "%3D",
            '&' to "%26",
            '%' to "%25",
            '?' to "%3F",
            '#' to "%23",
            '@' to "%40",
            '!' to "%21",
            '$' to "%24",
            '\'' to "%27",
            '"' to "%22",
            ' ' to "%20"
        )
    }
}

/**
 * Warning event for a short secret that was not registered for masking.
 *
 * ## Who builds it and who reads it
 * The seam that BOUNDS a credential builds it — it is the one place that knows which credential
 * a value belongs to — and the operator's console reads it. The registry itself does not: it
 * discards a short value in silence, because its registration reads through
 * `SecretHandle.peek`, whose contract cannot carry a result out. See the class KDoc.
 *
 * ## What it must never carry
 * The secret. A report about a secret that carries the secret is a second copy of it, in a
 * place that is not protected the way the binding is.
 *
 * @param credentialsId The credential ID that was not masked
 * @param length The actual length of the secret value
*/
data class SecretShorterThanMinimumMaskableLengthWarning(
    val credentialsId: String,
    val length: Int,
)
